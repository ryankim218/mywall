create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_name text not null default 'Ryan Kim',
  message text not null,
  photo_url text,
  created_at timestamptz not null default now(),

  constraint posts_message_length
    check (char_length(message) between 1 and 280),

  constraint posts_message_not_blank
    check (length(trim(message)) > 0)
);

alter table public.posts
add column if not exists photo_url text;

alter table public.posts enable row level security;

drop policy if exists "Anyone can read wall posts" on public.posts;
create policy "Anyone can read wall posts"
on public.posts
for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can publish wall posts" on public.posts;
create policy "Anyone can publish wall posts"
on public.posts
for insert
to anon, authenticated
with check (
  user_name = 'Ryan Kim'
  and char_length(message) between 1 and 280
  and length(trim(message)) > 0
);

grant select, insert on public.posts to anon, authenticated;
grant usage, select on sequence public.posts_id_seq to anon, authenticated;

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'wall-photos',
  'wall-photos',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can read wall profile photos" on storage.objects;
drop policy if exists "Anyone can upload the wall profile photo" on storage.objects;
drop policy if exists "Anyone can replace the wall profile photo" on storage.objects;
drop policy if exists "Anyone can read wall post photos" on storage.objects;
create policy "Anyone can read wall post photos"
on storage.objects
for select
to anon, authenticated
using (
  bucket_id = 'wall-photos'
  and (storage.foldername(name))[1] = 'posts'
);

drop policy if exists "Anyone can upload wall post photos" on storage.objects;
create policy "Anyone can upload wall post photos"
on storage.objects
for insert
to anon, authenticated
with check (
  bucket_id = 'wall-photos'
  and (storage.foldername(name))[1] = 'posts'
);
